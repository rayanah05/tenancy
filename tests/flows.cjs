const { chromium } = require('playwright')
const B = 'http://localhost:4173'
const results = []
const check = (name, ok, extra = '') => results.push(`${ok ? 'PASS' : 'FAIL'}  ${name}${extra ? ' — ' + extra : ''}`)
;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await ctx.addInitScript(() => localStorage.setItem('tenancy-lang', 'en'))
  const p = await ctx.newPage()
  const errs = []; p.on('pageerror', (e) => errs.push(String(e)))

  // 1. Sign-up flow with validation
  await p.goto(B + '/'); await p.getByRole('link', { name: 'Create account' }).first().click()
  await p.getByRole('button', { name: 'Create account' }).click()
  check('Register: empty form shows error summary', await p.getByRole('alert').filter({ hasText: '3 problem' }).isVisible())
  check('Register: fields marked invalid', (await p.locator('[aria-invalid="true"]').count()) === 3)
  await p.getByLabel('Full name').fill('Sara Ahmed'); await p.getByLabel('Email').fill('sara@email.com'); await p.getByLabel('Password').fill('tenancy1234')
  await p.getByRole('button', { name: 'Create account' }).click()
  check('Register → Verify email shows the address', await p.getByText('sara@email.com').isVisible())
  await p.getByRole('button', { name: 'Resend link' }).click()
  check('Verify: resend shows feedback', await p.getByText('A new link is on its way.').isVisible())
  await p.getByRole('link', { name: "I've verified my email" }).click()
  check('Verify → Welcome (choose path)', p.url().endsWith('/welcome'))
  await p.getByRole('link', { name: 'Add a property' }).click()
  await p.getByRole('button', { name: 'Save property' }).click()
  check('Add property: required errors', (await p.locator('[aria-invalid="true"]').count()) === 2)
  await p.getByLabel('Property name').fill('Flat 20'); await p.getByLabel('Address').fill('Road 1, Juffair')
  await p.getByRole('button', { name: 'Save property' }).click()
  check('Add property → property page + toast', p.url().includes('/landlord/properties/flat-12') && await p.getByRole('status').filter({ hasText: 'Flat 20' }).isVisible())

  // 2. Log in error and success
  await p.goto(B + '/login'); await p.getByLabel('Email').fill('khalid@email.com'); await p.getByLabel('Password').fill('wrongpass')
  await p.getByRole('button', { name: 'Log in' }).click()
  check('Log in: wrong password shows error alert', await p.getByRole('alert').filter({ hasText: 'Wrong email or password' }).isVisible())
  check('Log in: password field flagged', (await p.getByLabel('Password').getAttribute('aria-invalid')) === 'true')
  await p.getByLabel('Password').fill('tenancy123'); await p.getByRole('button', { name: 'Log in' }).click()
  check('Log in → landlord dashboard', p.url().endsWith('/landlord'))

  // 3. Landlord: dashboard → rent → reject dialog
  await p.getByRole('link', { name: /Payment proof to review/ }).click()
  check('Dashboard action → Rent tab', p.url().endsWith('/flat-12/rent'))
  await p.getByRole('button', { name: 'Reject' }).click()
  const dlg = p.getByRole('dialog', { name: 'Reject this payment?' })
  check('Reject opens a labelled dialog', await dlg.isVisible())
  check('Dialog moves focus inside', await p.evaluate(() => !!document.activeElement.closest('[role=dialog]')))
  await p.getByRole('button', { name: 'Reject payment' }).click()
  check('Dialog: reason is required', await dlg.getByText('Give a reason').isVisible())
  await p.keyboard.press('Escape')
  check('Escape closes dialog and returns focus', !(await dlg.isVisible()) && (await p.evaluate(() => document.activeElement.textContent)) === 'Reject')
  await p.getByRole('button', { name: 'Reject' }).click(); await p.getByLabel('Reason').fill('Amount does not match')
  await p.getByRole('button', { name: 'Reject payment' }).click()
  check('Reject with reason → status Rejected + feedback', await p.getByText('Rejected', { exact: true }).isVisible() && await p.getByRole('status').filter({ hasText: 'rejected' }).isVisible())
  await p.getByRole('link', { name: 'Requests' }).click(); await p.getByRole('link', { name: /Leaking kitchen tap/ }).click()
  await p.getByLabel('Status').selectOption('inProgress'); await p.getByRole('button', { name: 'Save update' }).click()
  check('Request update → back to list + feedback', p.url().endsWith('/requests') && await p.getByRole('status').filter({ hasText: 'Update saved' }).isVisible())
  await p.getByRole('button', { name: 'Fixed' }).click()
  check('Filter chips toggle (aria-pressed)', (await p.getByRole('button', { name: 'Fixed' }).getAttribute('aria-pressed')) === 'true')

  // 4. Role switch + tenant flows
  await p.goto(B + '/landlord'); await p.getByRole('group', { name: 'Mode' }).getByRole('link', { name: 'Tenant' }).click()
  check('Role switch → tenant dashboard', p.url().endsWith('/tenant'))
  check('Bottom tabs change to tenant (My lease)', await p.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'My lease' }).isVisible())
  await p.getByRole('link', { name: 'Pay rent' }).click(); await p.getByRole('button', { name: 'Submit proof' }).click()
  check('Pay rent: missing date + file errors', await p.getByText('Enter the date you paid.').isVisible() && await p.getByText('Upload a screenshot or PDF').isVisible())
  await p.getByLabel('Payment date').fill('2026-11-30')
  await p.locator('input[type=file]').setInputFiles({ name: 'transfer.png', mimeType: 'image/png', buffer: Buffer.from('x') })
  await p.getByRole('button', { name: 'Submit proof' }).click()
  check('Pay rent → Proof submitted (success state)', p.url().endsWith('/pay/submitted') && await p.getByText('Proof submitted').isVisible())
  await p.getByRole('link', { name: 'View rent history' }).click()
  check('Submitted → History', p.url().endsWith('/history'))
  await p.goto(B + '/tenant/lease/requests'); await p.getByRole('link', { name: 'New request' }).click()
  await p.getByLabel('What needs fixing?').fill('Broken window'); await p.getByRole('button', { name: 'Send request' }).click()
  check('New request: photo required error', await p.getByText('Add at least one photo').isVisible())
  await p.locator('input[type=file]').setInputFiles({ name: 'window.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('x') })
  await p.getByRole('button', { name: 'Send request' }).click()
  check('New request → status page + feedback', p.url().includes('/requests/r1') && await p.getByRole('status').filter({ hasText: 'Request sent' }).isVisible())
  check('Mobile back button on inner page', await p.getByRole('button', { name: 'Back' }).isVisible())
  await p.getByRole('button', { name: 'Back' }).click()
  check('Back returns to previous page', p.url().endsWith('/requests/new') || p.url().endsWith('/requests'))
  await p.goto(B + '/tenant/invite'); await p.getByRole('button', { name: 'Accept lease' }).click()
  check('Accept invite → My lease', p.url().endsWith('/tenant/lease'))

  // 5. Shared pages, language, keyboard
  await p.goto(B + '/tenant'); await p.getByRole('link', { name: /Open notifications/ }).click()
  check('Bell → Notifications', p.url().endsWith('/notifications'))
  await p.getByRole('switch').click()
  check('Email reminders switch toggles', (await p.getByRole('switch').getAttribute('aria-checked')) === 'false')
  await p.goto(B + '/settings'); await p.getByRole('link', { name: /Profile/ }).first().click()
  await p.getByLabel('Email').fill('bad'); await p.getByRole('button', { name: 'Save changes' }).click()
  check('Profile: invalid email error', await p.getByText('Enter a valid email').isVisible())
  await p.getByLabel('Email').fill('khalid@email.com'); await p.getByRole('button', { name: 'Save changes' }).click()
  check('Profile save → Settings + feedback', p.url().endsWith('/settings') && await p.getByRole('status').filter({ hasText: 'Changes saved' }).isVisible())
  await p.getByRole('button', { name: /Language/ }).first().click()
  check('Language switch → Arabic, right-to-left', (await p.evaluate(() => document.documentElement.dir)) === 'rtl' && await p.getByRole('heading', { name: 'الإعدادات' }).isVisible())
  { const fresh = await browser.newPage(); await fresh.goto(B + '/settings'); await fresh.getByRole('button', { name: /Language/ }).first().click(); await fresh.reload()
    check('Language choice is remembered after reload', (await fresh.evaluate(() => document.documentElement.lang)) === 'ar'); await fresh.close() }
  await p.evaluate(() => localStorage.setItem('tenancy-lang', 'en')); await p.goto(B + '/landlord')
  await p.keyboard.press('Tab')
  check('Keyboard: first Tab reaches "Skip to main content"', (await p.evaluate(() => document.activeElement.textContent)) === 'Skip to main content')
  await p.goto(B + '/nope'); check('Unknown URL → friendly 404', await p.getByText('Page not found').isVisible())

  // 6. Desktop sidebar
  const d = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await d.goto(B + '/landlord'); await d.getByRole('complementary').getByRole('link', { name: 'Properties' }).click()
  check('Desktop sidebar → Properties (active state)', d.url().endsWith('/landlord/properties') && (await d.getByRole('complementary').getByRole('link', { name: 'Properties' }).getAttribute('aria-current')) === 'page')
  check('No JavaScript errors during all flows', errs.length === 0, errs[0])
  await browser.close()
  console.log(results.join('\n'))
  console.log(`\n${results.filter((r) => r.startsWith('PASS')).length}/${results.length} passed`)
})()
